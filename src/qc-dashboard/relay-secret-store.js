// BO Relay — self-service secret store (admin-writable, gitignored).
//
// Persistence file: data/relay-secret.local.json  — matches the *.local.json
// pattern in .gitignore, so it never lands in the repo. Directory-scoped
// so the same protection that guards data/bo-sites-runtime.json applies.
//
// Precedence when the server reads the secret:
//   1. RELAY_SECRET environment variable  (IT-managed override)
//   2. data/relay-secret.local.json:secret  (admin-managed via the QC Hub)
// This lets IT still override in production if they ever want to; day-to-day
// operations run entirely from admin UI without server access.
//
// The value is:
//   - Generated by crypto.randomBytes(32) → hex → 64 chars (32 real bytes)
//   - Written to disk with restrictive permissions (0600 where the FS honours it)
//   - Returned to the admin ONCE in the rotate response
//   - Never returned again by health/config/any other endpoint
//   - Never logged

import { readFileSync, writeFileSync, existsSync, mkdirSync, chmodSync, renameSync, unlinkSync } from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const DEFAULT_SECRET_FILE = process.env.QC_RELAY_SECRET_FILE
  || path.resolve('data', 'relay-secret.local.json');
const MIN_BYTES = 32;

// Rotation invalidation callbacks are registered by callers (job store,
// worker heartbeat cache). On every successful rotate, all pending state
// tied to the OLD secret gets cleared — correction brief §1.
const _invalidationHooks = new Set();
export function registerRotationInvalidation(fn) {
  if (typeof fn === 'function') _invalidationHooks.add(fn);
}
export function _clearInvalidationHooksForTest() { _invalidationHooks.clear(); }
function _runInvalidation(reason) {
  for (const fn of _invalidationHooks) {
    try { fn(reason); } catch (e) { try { console.warn(`[relay-secret] invalidation hook failed: ${e?.message || 'unknown'}`); } catch {} }
  }
}

// ── Read (never returns the value in error paths) ──────────────────────

export function readPersistedSecret({ file = DEFAULT_SECRET_FILE } = {}) {
  if (!existsSync(file)) return { present: false, secret: null, meta: null };
  let raw;
  try { raw = readFileSync(file, 'utf8'); } catch { return { present: false, secret: null, meta: null }; }
  let parsed;
  try { parsed = JSON.parse(raw); } catch { return { present: false, secret: null, meta: null }; }
  const secret = typeof parsed?.secret === 'string' ? parsed.secret : null;
  if (!secret || Buffer.byteLength(secret, 'utf8') < MIN_BYTES) {
    return { present: false, secret: null, meta: null };
  }
  return {
    present: true,
    secret,
    meta: {
      rotatedAt: parsed.rotatedAt || null,
      rotatedBy: parsed.rotatedBy || null,
    },
  };
}

// Public status shape — never carries the value.
export function readStatus({ file = DEFAULT_SECRET_FILE, env = process.env } = {}) {
  // Env-set secret wins; report source honestly but never the value.
  if (env.RELAY_SECRET && Buffer.byteLength(env.RELAY_SECRET, 'utf8') >= MIN_BYTES) {
    return { configured: true, source: 'env', lastRotatedAt: null, lastRotatedBy: null };
  }
  const persisted = readPersistedSecret({ file });
  if (persisted.present) {
    return {
      configured: true, source: 'file',
      lastRotatedAt: persisted.meta.rotatedAt,
      lastRotatedBy: persisted.meta.rotatedBy,
    };
  }
  return { configured: false, source: null, lastRotatedAt: null, lastRotatedBy: null };
}

// The value the auth layer actually uses. env wins; file is fallback.
export function readEffectiveSecret({ file = DEFAULT_SECRET_FILE, env = process.env } = {}) {
  if (env.RELAY_SECRET && Buffer.byteLength(env.RELAY_SECRET, 'utf8') >= MIN_BYTES) {
    return env.RELAY_SECRET;
  }
  const persisted = readPersistedSecret({ file });
  return persisted.present ? persisted.secret : null;
}

// ── Rotate ─────────────────────────────────────────────────────────────

// Generates a fresh 32-byte hex secret, writes it atomically to disk,
// calls invalidation hooks (clears in-flight jobs + worker heartbeats +
// replay nonces), and returns the value ONCE. Caller MUST send
// Cache-Control: no-store and MUST never persist the returned value in
// any log.
//
// `env` is passed so the caller can enforce env-precedence policy (§3 of
// the pre-deploy checks). When RELAY_SECRET is env-set, rotate throws
// EXTERNALLY_MANAGED — the admin UI surfaces that to the operator.
export function rotateSecret({ actorEmail, file = DEFAULT_SECRET_FILE, now = new Date(), env = process.env, allowEnvOverride = false } = {}) {
  if (!actorEmail || typeof actorEmail !== 'string') {
    throw new Error('rotateSecret: actorEmail required');
  }
  if (!allowEnvOverride && env.RELAY_SECRET && Buffer.byteLength(env.RELAY_SECRET, 'utf8') >= MIN_BYTES) {
    const err = new Error('RELAY_SECRET is externally managed via environment; rotate at the source (or unset the env var to switch to admin-managed).');
    err.code = 'EXTERNALLY_MANAGED';
    throw err;
  }
  const secret = crypto.randomBytes(32).toString('hex'); // 64 chars, 32 bytes of entropy
  const payload = {
    secret,
    rotatedAt: now.toISOString(),
    rotatedBy: String(actorEmail).slice(0, 200),
  };
  const dir = path.dirname(file);
  try { if (!existsSync(dir)) mkdirSync(dir, { recursive: true }); } catch {}
  // Atomic-ish write: put the new content in a sibling temp file, THEN
  // renameSync onto the destination. rename is atomic on POSIX and on
  // Windows filesystems that back local paths. A crash mid-write leaves
  // the original file intact (or the file simply absent on a first-time
  // rotate), never a truncated JSON that would look like "not configured
  // but was configured a moment ago".
  const tmp = `${file}.tmp-${process.pid}-${Date.now()}`;
  try {
    writeFileSync(tmp, JSON.stringify(payload, null, 2), { encoding: 'utf8', mode: 0o600 });
    try { chmodSync(tmp, 0o600); } catch {}  // POSIX honours; Windows ignores
    renameSync(tmp, file);
    try { chmodSync(file, 0o600); } catch {}  // final belt-and-braces
  } catch (e) {
    try { unlinkSync(tmp); } catch {}
    throw e;
  }
  _runInvalidation('rotated');
  return { secret, rotatedAt: payload.rotatedAt, rotatedBy: payload.rotatedBy };
}
